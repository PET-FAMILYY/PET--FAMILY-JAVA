-- Gatilhos nao podem ficar dentro de um pacote Oracle.
-- Este e um gatilho fino: chama a rotina do pacote, respeitando o empacotamento.
CREATE OR REPLACE TRIGGER trg_pf_auditoria_s4
AFTER INSERT OR UPDATE OR DELETE ON consultas
    FOR EACH ROW
BEGIN
  IF INSERTING THEN
    pkg_petfamily_s4.pr_registrar_auditoria(:NEW.id,'INSERT',NULL,:NEW.status);
  ELSIF UPDATING THEN
    pkg_petfamily_s4.pr_registrar_auditoria(:NEW.id,'UPDATE',:OLD.status,:NEW.status);
ELSE
    pkg_petfamily_s4.pr_registrar_auditoria(:OLD.id,'DELETE',:OLD.status,NULL);
END IF;
END;
