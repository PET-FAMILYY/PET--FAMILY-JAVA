-- PET FAMILY | Sprint 4 | Oracle 19c+ | Modelo fisico alinhado ao projeto Java
-- EXECUTAR APENAS NUM SCHEMA Oracle de teste sem as tabelas existentes.
-- Os nomes/colunas preservam o dominio do Pet Family Spring Boot.
-- Identidades iniciam em 1000 para nao conflitar com registros de demonstracao 1-10.

CREATE TABLE tutores (
                         id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
                         nome VARCHAR2(255 CHAR) NOT NULL,
                         email VARCHAR2(255 CHAR) NOT NULL UNIQUE,
                         telefone VARCHAR2(50 CHAR)
);
CREATE TABLE pets (
                      id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
                      nome VARCHAR2(255 CHAR) NOT NULL,
                      especie VARCHAR2(100 CHAR) NOT NULL,
                      raca VARCHAR2(100 CHAR),
                      idade NUMBER(10),
                      peso BINARY_DOUBLE,
                      observacoes_saude CLOB,
                      tutor_id NUMBER(19) NOT NULL REFERENCES tutores(id),
                      CONSTRAINT ck_pf_pet_idade CHECK (idade IS NULL OR idade >= 0),
                      CONSTRAINT ck_pf_pet_peso CHECK (peso IS NULL OR peso > 0)
);
CREATE INDEX idx_pf_pet_tutor ON pets(tutor_id);
CREATE TABLE usuarios (
                          id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
                          nome VARCHAR2(150 CHAR) NOT NULL,
                          email VARCHAR2(255 CHAR) NOT NULL UNIQUE,
                          senha_hash VARCHAR2(255 CHAR) NOT NULL,
                          role VARCHAR2(20 CHAR) NOT NULL,
                          tutor_id NUMBER(19) UNIQUE REFERENCES tutores(id) ON DELETE CASCADE,
                          criado_em TIMESTAMP(6) NOT NULL,
                          CONSTRAINT ck_pf_usuario_role CHECK (role IN ('TUTOR','VETERINARIO'))
);
CREATE TABLE consultas (
                           id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
                           data DATE NOT NULL,
                           horario TIMESTAMP(6),
                           tipo_consulta VARCHAR2(150 CHAR) NOT NULL,
                           status VARCHAR2(20 CHAR) NOT NULL,
                           observacoes CLOB,
                           pet_id NUMBER(19) NOT NULL REFERENCES pets(id),
                           criado_em TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
                           realizada_em TIMESTAMP(6),
                           realizada_por_usuario_id NUMBER(19) REFERENCES usuarios(id),
                           CONSTRAINT ck_pf_status_consulta CHECK (status IN ('AGENDADA','REALIZADA','CANCELADA')),
                           CONSTRAINT ck_pf_consulta_hora CHECK (status <> 'AGENDADA' OR horario IS NOT NULL)
);
CREATE INDEX idx_pf_consultas_pet ON consultas(pet_id);
CREATE INDEX idx_pf_consultas_data ON consultas(data);
CREATE INDEX idx_pf_consultas_status ON consultas(status);
CREATE TABLE consulta_slots (
                                id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
                                data DATE NOT NULL,
                                horario TIMESTAMP(6) NOT NULL,
                                consulta_id NUMBER(19) NOT NULL UNIQUE REFERENCES consultas(id) ON DELETE CASCADE,
                                CONSTRAINT uk_pf_slot UNIQUE(data,horario)
);
CREATE TABLE lembretes (
                           id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
                           titulo VARCHAR2(255 CHAR) NOT NULL,
                           descricao CLOB,
                           data_lembrete DATE NOT NULL,
                           tipo VARCHAR2(100 CHAR) NOT NULL,
                           status VARCHAR2(20 CHAR) NOT NULL,
                           pet_id NUMBER(19) NOT NULL REFERENCES pets(id),
                           recorrencia_dias NUMBER(10),
                           data_conclusao DATE,
                           criado_por_usuario_id NUMBER(19) REFERENCES usuarios(id),
                           concluido_por_usuario_id NUMBER(19) REFERENCES usuarios(id),
                           origem_lembrete_id NUMBER(19) REFERENCES lembretes(id) ON DELETE SET NULL,
                           CONSTRAINT ck_pf_status_lembrete CHECK (status IN ('PENDENTE','CONCLUIDO','CANCELADO')),
                           CONSTRAINT ck_pf_recorrencia CHECK (recorrencia_dias IS NULL OR recorrencia_dias >= 1)
);
CREATE INDEX idx_pf_lembretes_pet ON lembretes(pet_id);
CREATE INDEX idx_pf_lembretes_status ON lembretes(status);
CREATE TABLE interacoes_ia (
                               id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
                               pergunta CLOB NOT NULL,
                               resposta CLOB NOT NULL,
                               data_hora TIMESTAMP(6) NOT NULL,
                               categoria VARCHAR2(100 CHAR),
                               pet_id NUMBER(19) NOT NULL REFERENCES pets(id)
);
CREATE INDEX idx_pf_interacoes_pet ON interacoes_ia(pet_id);
CREATE TABLE auditoria_consultas_s4 (
                                        id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
                                        consulta_id NUMBER(19),
                                        operacao VARCHAR2(10 CHAR) NOT NULL,
                                        status_antigo VARCHAR2(20 CHAR),
                                        status_novo VARCHAR2(20 CHAR),
                                        usuario_bd VARCHAR2(128 CHAR) NOT NULL,
                                        instante TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL
);
-- Pacote PL/SQL da Sprint 4: especificacao publica.
-- Todos os procedimentos operam sobre as mesmas tabelas do modelo Pet Family.
CREATE OR REPLACE PACKAGE pkg_petfamily_s4 AS
  FUNCTION fn_status_valido(p_status IN VARCHAR2) RETURN NUMBER;
  FUNCTION fn_contar_pets(p_tutor_id IN NUMBER) RETURN NUMBER;
  PROCEDURE pr_cadastrar_tutor(p_nome IN VARCHAR2,p_email IN VARCHAR2,p_telefone IN VARCHAR2,p_id OUT NUMBER);
  PROCEDURE pr_cadastrar_pet(p_tutor_id IN NUMBER,p_nome IN VARCHAR2,p_especie IN VARCHAR2,p_id OUT NUMBER);
  PROCEDURE pr_agendar_consulta(p_pet_id IN NUMBER,p_data IN DATE,p_horario IN VARCHAR2,p_tipo IN VARCHAR2,p_id OUT NUMBER);
  PROCEDURE pr_atualizar_status(p_consulta_id IN NUMBER,p_status IN VARCHAR2);
  PROCEDURE pr_registrar_auditoria(p_id IN NUMBER,p_operacao IN VARCHAR2,p_anterior IN VARCHAR2,p_novo IN VARCHAR2);
  PROCEDURE pr_exportar_json(p_colecao IN VARCHAR2,p_json OUT CLOB);
END pkg_petfamily_s4;
/
-- Corpo do pacote - encapsulamento, verificacoes e tratamento de excecoes.
-- Oracle 19c+ (usa JSON_OBJECT RETURNING CLOB).
CREATE OR REPLACE PACKAGE BODY pkg_petfamily_s4 AS

  -- Helpers PRIVADOS, nao expostos na especificacao.
  PROCEDURE iniciar_array(p_json OUT CLOB) IS
BEGIN
    DBMS_LOB.CREATETEMPORARY(p_json, TRUE);
    DBMS_LOB.WRITEAPPEND(p_json, 1, '[');
END;
  PROCEDURE texto(p_json IN OUT NOCOPY CLOB,p_txt IN VARCHAR2) IS
BEGIN
    IF p_txt IS NOT NULL THEN
      DBMS_LOB.WRITEAPPEND(p_json, LENGTH(p_txt), p_txt);
END IF;
END;
  PROCEDURE adicionar(p_array IN OUT NOCOPY CLOB,p_item IN CLOB,p_primeiro IN OUT BOOLEAN) IS
BEGIN
    IF NOT p_primeiro THEN texto(p_array, ','); END IF;
    DBMS_LOB.APPEND(p_array, p_item);
    p_primeiro := FALSE;
END;
  PROCEDURE fechar_array(p_array IN OUT NOCOPY CLOB) IS
BEGIN
    texto(p_array, ']');
END;
  FUNCTION status_ok(p_status IN VARCHAR2) RETURN BOOLEAN IS
BEGIN
RETURN p_status IN ('AGENDADA','REALIZADA','CANCELADA');
END;
  PROCEDURE erro(p_codigo IN NUMBER,p_msg IN VARCHAR2) IS
BEGIN
    RAISE_APPLICATION_ERROR(p_codigo,p_msg);
END;

  FUNCTION fn_status_valido(p_status IN VARCHAR2) RETURN NUMBER IS
BEGIN
    IF status_ok(UPPER(TRIM(p_status))) THEN RETURN 1; END IF;
RETURN 0;
END;

  FUNCTION fn_contar_pets(p_tutor_id IN NUMBER) RETURN NUMBER IS
    v_existe NUMBER;
    v_qtd NUMBER;
BEGIN
SELECT COUNT(*) INTO v_existe FROM tutores WHERE id = p_tutor_id;
IF v_existe = 0 THEN erro(-20004,'Tutor nao encontrado.'); END IF;
SELECT COUNT(*) INTO v_qtd FROM pets WHERE tutor_id = p_tutor_id;
RETURN v_qtd;
END;

  PROCEDURE pr_cadastrar_tutor(p_nome IN VARCHAR2,p_email IN VARCHAR2,p_telefone IN VARCHAR2,p_id OUT NUMBER) IS
    v_qtd NUMBER;
BEGIN
    IF TRIM(p_nome) IS NULL OR TRIM(p_email) IS NULL THEN
      erro(-20001,'Nome e e-mail sao obrigatorios.');
END IF;
    IF NOT REGEXP_LIKE(p_email,'^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$') THEN
      erro(-20005,'E-mail invalido.');
END IF;
SELECT COUNT(*) INTO v_qtd FROM tutores WHERE LOWER(email) = LOWER(TRIM(p_email));
IF v_qtd > 0 THEN erro(-20006,'E-mail ja cadastrado.'); END IF;
INSERT INTO tutores(nome,email,telefone) VALUES (TRIM(p_nome),LOWER(TRIM(p_email)),p_telefone)
    RETURNING id INTO p_id;
EXCEPTION
    WHEN DUP_VAL_ON_INDEX THEN erro(-20006,'E-mail ja cadastrado.');
WHEN VALUE_ERROR THEN erro(-20005,'Valor invalido para cadastrar tutor.');
END;

  PROCEDURE pr_cadastrar_pet(p_tutor_id IN NUMBER,p_nome IN VARCHAR2,p_especie IN VARCHAR2,p_id OUT NUMBER) IS
    v_qtd NUMBER;
BEGIN
    IF p_tutor_id IS NULL OR TRIM(p_nome) IS NULL OR TRIM(p_especie) IS NULL THEN
      erro(-20001,'Tutor, nome e especie sao obrigatorios.');
END IF;
SELECT COUNT(*) INTO v_qtd FROM tutores WHERE id=p_tutor_id;
IF v_qtd=0 THEN erro(-20004,'Tutor nao encontrado.'); END IF;
INSERT INTO pets(tutor_id,nome,especie) VALUES(p_tutor_id,TRIM(p_nome),TRIM(p_especie))
    RETURNING id INTO p_id;
EXCEPTION
    WHEN VALUE_ERROR THEN erro(-20005,'Valor invalido para cadastrar pet.');
END;

  PROCEDURE pr_agendar_consulta(p_pet_id IN NUMBER,p_data IN DATE,p_horario IN VARCHAR2,p_tipo IN VARCHAR2,p_id OUT NUMBER) IS
    v_qtd NUMBER;
    v_hora TIMESTAMP;
    v_data DATE;
BEGIN
    IF p_pet_id IS NULL OR p_data IS NULL OR TRIM(p_horario) IS NULL OR TRIM(p_tipo) IS NULL THEN
      erro(-20001,'Pet, data, horario e tipo sao obrigatorios.');
END IF;
SELECT COUNT(*) INTO v_qtd FROM pets WHERE id = p_pet_id;
IF v_qtd = 0 THEN erro(-20004,'Pet nao encontrado.'); END IF;
    IF NOT REGEXP_LIKE(p_horario,'^([01][0-9]|2[0-3]):[0-5][0-9]$') THEN
      erro(-20005,'Horario deve estar em HH24:MI.');
END IF;
    v_data := TRUNC(p_data);
    v_hora := TO_TIMESTAMP(TO_CHAR(v_data,'YYYY-MM-DD') || ' ' || p_horario || ':00','YYYY-MM-DD HH24:MI:SS');
SELECT COUNT(*) INTO v_qtd FROM consulta_slots WHERE data = v_data AND horario = v_hora;
IF v_qtd > 0 THEN erro(-20009,'Horario ja esta reservado.'); END IF;
INSERT INTO consultas(data,horario,tipo_consulta,status,pet_id)
VALUES(v_data,v_hora,TRIM(p_tipo),'AGENDADA',p_pet_id) RETURNING id INTO p_id;
INSERT INTO consulta_slots(data,horario,consulta_id) VALUES(v_data,v_hora,p_id);
EXCEPTION
    WHEN DUP_VAL_ON_INDEX THEN erro(-20009,'Horario ja esta reservado.');
WHEN VALUE_ERROR THEN erro(-20005,'Valor invalido ao agendar consulta.');
END;

  PROCEDURE pr_atualizar_status(p_consulta_id IN NUMBER,p_status IN VARCHAR2) IS
    v_status VARCHAR2(20):=UPPER(TRIM(p_status));
    v_anterior VARCHAR2(20);
    v_data DATE;
    v_hora TIMESTAMP;
BEGIN
    IF p_consulta_id IS NULL OR p_status IS NULL THEN erro(-20001,'Consulta e status obrigatorios.'); END IF;
    IF NOT status_ok(v_status) THEN erro(-20005,'Status deve ser AGENDADA, REALIZADA ou CANCELADA.'); END IF;
SELECT status,data,horario INTO v_anterior,v_data,v_hora FROM consultas WHERE id=p_consulta_id FOR UPDATE;
IF v_status='AGENDADA' AND v_hora IS NULL THEN erro(-20005,'Consulta agendada exige horario.'); END IF;
UPDATE consultas SET status=v_status,
                     realizada_em=CASE WHEN v_status='REALIZADA' THEN SYSTIMESTAMP ELSE NULL END
WHERE id=p_consulta_id;
IF v_anterior='AGENDADA' AND v_status <> 'AGENDADA' THEN
DELETE FROM consulta_slots WHERE consulta_id=p_consulta_id;
ELSIF v_anterior <> 'AGENDADA' AND v_status='AGENDADA' THEN
      INSERT INTO consulta_slots(data,horario,consulta_id) VALUES(v_data,v_hora,p_consulta_id);
END IF;
EXCEPTION
    WHEN NO_DATA_FOUND THEN erro(-20004,'Consulta nao encontrada.');
WHEN DUP_VAL_ON_INDEX THEN erro(-20009,'Horario ja reservado para outra consulta.');
END;

  PROCEDURE pr_registrar_auditoria(p_id IN NUMBER,p_operacao IN VARCHAR2,p_anterior IN VARCHAR2,p_novo IN VARCHAR2) IS
BEGIN
INSERT INTO auditoria_consultas_s4(consulta_id,operacao,status_antigo,status_novo,usuario_bd)
VALUES(p_id,p_operacao,p_anterior,p_novo,SYS_CONTEXT('USERENV','SESSION_USER'));
END;

  PROCEDURE pr_exportar_json(p_colecao IN VARCHAR2,p_json OUT CLOB) IS
    v_item CLOB; v_pet CLOB; v_pets CLOB; v_lembretes CLOB;
    v_primeiro BOOLEAN:=TRUE; v_primeiro_pet BOOLEAN; v_primeiro_lembrete BOOLEAN;
    v_data VARCHAR2(24); v_hora VARCHAR2(5);
BEGIN
    IF UPPER(TRIM(p_colecao)) NOT IN ('TUTORES','CONSULTAS','INTERACOES_IA') OR p_colecao IS NULL THEN
      erro(-20007,'Colecao deve ser TUTORES, CONSULTAS ou INTERACOES_IA.');
END IF;
    iniciar_array(p_json);
    IF UPPER(TRIM(p_colecao))='TUTORES' THEN
      FOR t IN (SELECT id,nome,email,telefone FROM tutores ORDER BY id) LOOP
        iniciar_array(v_pets); v_primeiro_pet:=TRUE;
FOR p IN (SELECT id,nome,especie,raca,idade,peso,observacoes_saude
                  FROM pets WHERE tutor_id=t.id ORDER BY id) LOOP
          iniciar_array(v_lembretes); v_primeiro_lembrete:=TRUE;
FOR l IN (SELECT id,titulo,descricao,data_lembrete,tipo,status,recorrencia_dias,data_conclusao
                    FROM lembretes WHERE pet_id=p.id ORDER BY id) LOOP
SELECT JSON_OBJECT(
               'id' VALUE l.id,'titulo' VALUE l.titulo,'descricao' VALUE l.descricao,
               'data_lembrete' VALUE TO_CHAR(l.data_lembrete,'YYYY-MM-DD'),
               'tipo' VALUE l.tipo,'status' VALUE l.status,
               'recorrencia_dias' VALUE l.recorrencia_dias,
               'data_conclusao' VALUE TO_CHAR(l.data_conclusao,'YYYY-MM-DD')
              RETURNING CLOB) INTO v_item FROM dual;
adicionar(v_lembretes,v_item,v_primeiro_lembrete);
END LOOP;
          fechar_array(v_lembretes);
SELECT JSON_OBJECT(
               'id' VALUE p.id,'nome' VALUE p.nome,'especie' VALUE p.especie,
               'raca' VALUE p.raca,'idade' VALUE p.idade,'peso' VALUE p.peso,
               'observacoes_saude' VALUE p.observacoes_saude,
               'lembretes' VALUE v_lembretes FORMAT JSON RETURNING CLOB)
INTO v_pet FROM dual;
adicionar(v_pets,v_pet,v_primeiro_pet);
          DBMS_LOB.FREETEMPORARY(v_lembretes);
END LOOP;
        fechar_array(v_pets);
SELECT JSON_OBJECT('id' VALUE t.id,'nome' VALUE t.nome,
                   'email' VALUE t.email,'telefone' VALUE t.telefone,
                   'pets' VALUE v_pets FORMAT JSON RETURNING CLOB)
INTO v_item FROM dual;
adicionar(p_json,v_item,v_primeiro);
        DBMS_LOB.FREETEMPORARY(v_pets);
END LOOP;
    ELSIF UPPER(TRIM(p_colecao))='CONSULTAS' THEN
      FOR c IN (SELECT c.id,c.data,c.horario,c.tipo_consulta,c.status,c.observacoes,
                    c.criado_em,c.realizada_em,c.pet_id,p.nome pet_nome,p.tutor_id
                FROM consultas c JOIN pets p ON p.id=c.pet_id ORDER BY c.id) LOOP
SELECT JSON_OBJECT('id' VALUE c.pet_id,'nome' VALUE c.pet_nome,
                   'tutor_id' VALUE c.tutor_id RETURNING CLOB)
INTO v_pet FROM dual;
SELECT JSON_OBJECT(
               'id' VALUE c.id,'pet' VALUE v_pet FORMAT JSON,
               'data' VALUE TO_CHAR(c.data,'YYYY-MM-DD'),
               'horario' VALUE TO_CHAR(c.horario,'HH24:MI'),
               'tipo_consulta' VALUE c.tipo_consulta,'status' VALUE c.status,
               'observacoes' VALUE c.observacoes,
               'criado_em' VALUE TO_CHAR(c.criado_em,'YYYY-MM-DD"T"HH24:MI:SS'),
               'realizada_em' VALUE TO_CHAR(c.realizada_em,'YYYY-MM-DD"T"HH24:MI:SS')
          RETURNING CLOB) INTO v_item FROM dual;
adicionar(p_json,v_item,v_primeiro);
END LOOP;
ELSE
      FOR i IN (SELECT id,pet_id,pergunta,resposta,data_hora,categoria
                FROM interacoes_ia ORDER BY id) LOOP
SELECT JSON_OBJECT('id' VALUE i.id,'pet_id' VALUE i.pet_id,
                   'pergunta' VALUE i.pergunta,'resposta' VALUE i.resposta,
                   'data_hora' VALUE TO_CHAR(i.data_hora,'YYYY-MM-DD"T"HH24:MI:SS'),
                   'categoria' VALUE i.categoria RETURNING CLOB)
INTO v_item FROM dual;
adicionar(p_json,v_item,v_primeiro);
END LOOP;
END IF;
    fechar_array(p_json);
END;
END pkg_petfamily_s4;
